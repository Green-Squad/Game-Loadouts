import { chromium } from 'playwright';
import fs from 'node:fs';
const base='http://127.0.0.1:8080';
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:1280,height:900}});
const page=await context.newPage();
const failures=[];page.on('pageerror',e=>failures.push(e.message));
await page.goto(base+'/');
if(!(await page.textContent('body')).includes('Hand-Forged Edition'))throw Error('demo notice missing');
fs.mkdirSync('hand-forged/test-results',{recursive:true});
await page.screenshot({path:'hand-forged/test-results/home.png',fullPage:true});
await page.goto(base+'/login');
await page.locator('input[name=emailOrUsername]').fill('demo@handforged.invalid');
await page.locator('input[name=password]').fill('HandForgedDemo!');
await page.locator('#logInForm button[type=submit]').click();
await page.waitForURL(base+'/');
await page.goto(base+'/Call+of+Duty+Black+Ops+7/AK-27');
await page.locator('#storeForm label.loadoutButton').first().click();
await page.locator('#storeForm button[type=submit]').first().click();
await page.waitForLoadState('networkidle');
if((await page.textContent('body')).includes('not a valid loadout'))throw Error('original submit form failed');
await page.screenshot({path:'hand-forged/test-results/weapon-submitted.png',fullPage:true});
await page.setViewportSize({width:390,height:844});await page.goto(base+'/games');
await page.screenshot({path:'hand-forged/test-results/mobile-games.png',fullPage:true});
if(failures.length)throw Error('Browser errors: '+failures.join('; '));
await browser.close();console.log('PASS original rendered desktop/mobile login and submit forms');
