import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {chromium} from 'playwright';
const base=process.env.BASE_URL;
assert(['127.0.0.1','localhost'].includes(new URL(base).hostname),'Isolated loopback only');
const browser=await chromium.launch({headless:true,args:['--disable-dev-shm-usage']});
const context=await browser.newContext({viewport:{width:1440,height:1000}});
// External CAPTCHA and Disqus are separately covered by protocol fixtures. Do not contact them with test identities.
await context.route('**/*',route=>new URL(route.request().url()).origin===new URL(base).origin?route.continue():route.abort());
const page=await context.newPage();const errors=[],failures=[];page.on('pageerror',e=>errors.push(e.message));page.on('response',r=>{if(new URL(r.url()).origin===new URL(base).origin && r.status()>=400)failures.push([r.status(),new URL(r.url()).pathname]);});
const out=process.env.SCREENSHOT_DIR;await fs.mkdir(out,{recursive:true});
await page.goto(base+'/login',{waitUntil:'networkidle'});
assert(await page.evaluate(()=>document.styleSheets.length>=4),'stylesheets loaded');
await page.getByLabel('Email or username').fill('NewMember');await page.getByLabel('Password',{exact:true}).fill('changed-password');
await page.getByRole('button',{name:'Log in',exact:true}).click();await page.waitForURL('**/account');
assert(await page.getByRole('heading',{name:'Your account'}).isVisible());
await page.screenshot({path:out+'/account.png',fullPage:true});
await page.goto(base+'/Call+of+Duty+Modern+Warfare/M4A1');
await page.getByRole('link',{name:'Optic',exact:true}).click();
await page.locator('input[name="Optic"][value="1"]').check();
await page.getByRole('link',{name:'Barrel',exact:true}).click();
await page.locator('input[name="Barrel"][value="3"]').check();
await page.getByRole('button',{name:'Submit loadout',exact:true}).click();await page.waitForURL(/M4A1\/\d+$/);
assert(await page.getByRole('button',{name:/Remove vote/}).isVisible());
const id=new URL(page.url()).pathname.split('/').at(-1);
await page.getByRole('button',{name:/Remove vote/}).click();await page.waitForLoadState('networkidle');
assert(await page.getByRole('button',{name:/^Vote \(0\)/}).isVisible());
await page.getByRole('button',{name:/^Vote \(0\)/}).click();await page.waitForLoadState('networkidle');
assert(await page.getByRole('button',{name:/Remove vote \(1\)/}).isVisible());
await page.screenshot({path:out+'/loadout-voted.png',fullPage:true});
await page.goto(base+'/submissions');assert(await page.locator(`a[href$="/${id}"]`).count()>0);
assert(await page.locator('#submissions-table').isVisible());
await page.getByRole('columnheader',{name:'Weapon',exact:true}).click();
assert.equal(await page.locator('header a[href="/Call+of+Duty+Modern+Warfare"]').count(),1,'account navigation games present');
await page.screenshot({path:out+'/submissions.png',fullPage:true});
await page.setViewportSize({width:390,height:844});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'submissions mobile overflow');
await page.screenshot({path:out+'/mobile-submissions.png',fullPage:true});
await page.goto(base+'/account');
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'account mobile overflow');
await page.screenshot({path:out+'/mobile-account.png',fullPage:true});
await page.goto(base+'/logout');await page.getByRole('button',{name:'Log out',exact:true}).click();await page.waitForURL(base+'/');
await page.goto(base+'/account');await page.waitForURL('**/login');
await page.goto(base+'/join');assert(await page.getByLabel('Email',{exact:true}).isVisible());
await page.screenshot({path:out+'/mobile-join.png',fullPage:true});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'join mobile overflow');
assert.deepEqual(errors,[]);assert.deepEqual(failures,[]);await browser.close();console.log('PASS: native login, account, attachment selection, submission, vote removal, submissions, logout and mobile forms');
